// 💰 PAYMENTS & WALLET — Moola Core
// ==============================================

const balances = new Map();

// Helper: Get user balance
function getBalance(userId) {
  return balances.get(userId) || 100; // Starting balance
}

// Helper: Add Moola
function addMoola(userId, amount, description = '') {
  if (!userId || amount <= 0) return { success: false, error: 'Invalid input' };
  const current = getBalance(userId);
  const newBalance = current + amount;
  balances.set(userId, newBalance);
  console.log(`💰 ${description || 'Deposit'}: ${userId} +${amount} = ${newBalance}`);
  return { success: true, newBalance };
}

// Helper: Deduct Moola
function deductMoola(userId, amount, description = '') {
  if (!userId || amount <= 0) return { success: false, error: 'Invalid input' };
  const current = getBalance(userId);
  if (current < amount) return { success: false, error: 'Insufficient Moola', balance: current };
  const newBalance = current - amount;
  balances.set(userId, newBalance);
  console.log(`💸 ${description || 'Payment'}: ${userId} -${amount} = ${newBalance}`);
  return { success: true, newBalance };
}

// --- API Routes ---

// Get Wallet Balance
app.get('/api/wallet/:userId', (req, res) => {
  const balance = getBalance(req.params.userId);
  res.json({ userId: req.params.userId, balance });
});

// Top Up Moola
app.post('/api/wallet/topup', (req, res) => {
  const { userId, amount, currency = 'ZAR' } = req.body;
  if (!userId || !amount) {
    return res.status(400).json({ error: 'Missing fields' });
  }
  const result = addMoola(userId, amount, `Top-up (${currency})`);
  if (result.success) {
    dailyRevenue.moolaSales += amount;
  }
  res.json(result);
});

// Send Moola
app.post('/api/wallet/send', (req, res) => {
  const { fromUserId, toUserId, amount, note = '' } = req.body;
  if (!fromUserId || !toUserId || !amount) {
    return res.status(400).json({ error: 'Missing fields' });
  }
  if (fromUserId === toUserId) {
    return res.status(400).json({ error: 'Cannot send to yourself' });
  }
  const deduct = deductMoola(fromUserId, amount, `Sent to ${toUserId}`);
  if (!deduct.success) return res.status(400).json(deduct);
  
  addMoola(toUserId, amount, `From ${fromUserId}: ${note}`);
  res.json({ success: true, fromBalance: deduct.newBalance });
});

// Deduct Room Entry Fee
app.post('/api/chat/enter-room', (req, res) => {
  const { userId, roomId, entryFee } = req.body;
  if (!userId || !entryFee) {
    return res.status(400).json({ error: 'Missing fields' });
  }
  const result = deductMoola(userId, entryFee, `Room entry: ${roomId}`);
  res.json(result);
});

// Watch Ad → Earn Moola
app.post('/api/reward/ad-watched', (req, res) => {
  const { userId, reward = 50 } = req.body;
  if (!userId) return res.status(400).json({ error: 'Missing userId' });
  dailyRevenue.adViews++;
  const result = addMoola(userId, reward, 'Ad reward');
  res.json(result);
});

