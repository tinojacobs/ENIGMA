const express = require('express');
const http = require('http');
const { Server } = require('socket.io');
const cors = require('cors');
const path = require('path');

// --- Initialize App ---
const app = express();
const server = http.createServer(app);
const io = new Server(server, {
  cors: {
    origin: "*",
    methods: ["GET", "POST"]
  }
});

// --- Middleware ---
app.use(cors());
app.use(express.json());
app.use(express.static(path.join(__dirname, '../public')));

// --- In-Memory State ---
let activeUsers = {};
let activeRooms = {};
let drivers = {};
let activeRides = {};
let dailyRevenue = {
  chatMessages: 0,
  adViews: 0,
  moolaSales: 0,
  listingFees: 0,
  totalZAR: 0
};

// --- Socket.IO — Real-Time Chat ---
io.on('connection', (socket) => {
  console.log('✅ User connected:', socket.id);

  // User joins
  socket.on('user-online', (userData) => {
    activeUsers[socket.id] = {
      ...userData,
      online: true,
      lastSeen: new Date()
    };
    io.emit('users-online', Object.keys(activeUsers).length);
  });

  // Join chat room
  socket.on('join-room', (roomId, userId, userName) => {
    socket.join(roomId);
    if (!activeRooms[roomId]) activeRooms[roomId] = [];
    activeRooms[roomId].push({ id: userId, name: userName });
    
    io.to(roomId).emit('user-joined', {
      userId,
      userName,
      message: `${userName} joined the room 💜`
    });
    
    console.log(`📍 ${userName} joined ${roomId}`);
  });

  // Send message
  socket.on('send-message', async (data) => {
    const { roomId, text, senderName, senderId } = data;
    
    // Track revenue — each message = small cost
    dailyRevenue.chatMessages++;
    
    io.to(roomId).emit('receive-message', {
      text,
      senderName,
      senderId,
      timestamp: new Date().toISOString()
    });
  });

  // Typing indicator
  socket.on('typing', (roomId, userName) => {
    socket.to(roomId).emit('user-typing', userName);
  });

  // Disconnect
  socket.on('disconnect', () => {
    const user = activeUsers[socket.id];
    if (user) {
      Object.keys(activeRooms).forEach(roomId => {
        activeRooms[roomId] = activeRooms[roomId].filter(u => u.id !== user.userId);
      });
    }
    delete activeUsers[socket.id];
    io.emit('users-online', Object.keys(activeUsers).length);
    console.log('❌ User disconnected:', socket.id);
  });
});

