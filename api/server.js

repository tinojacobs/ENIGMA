// 🚕 RIDE-HAILING — Drivers • Fares • Payouts
// ==============================================

// Register Driver
app.post('/api/driver/register', (req, res) => {
  const { driverId, name, phone, vehicle } = req.body;
  if (!driverId || !name || !phone) {
    return res.status(400).json({ error: 'Missing required fields' });
  }
  drivers[driverId] = {
    driverId,
    name,
    phone,
    vehicle: vehicle || {},
    available: false,
    lat: null,
    lng: null,
    totalTrips: 0,
    totalEarnings: 0,
    joinedAt: new Date()
  };
  res.json({ success: true, driver: drivers[driverId] });
});

// Update Driver Location & Availability
app.post('/api/driver/location', (req, res) => {
  const { driverId, lat, lng, available } = req.body;
  if (!drivers[driverId]) {
    return res.status(404).json({ error: 'Driver not found' });
  }
  if (lat !== undefined) drivers[driverId].lat = lat;
  if (lng !== undefined) drivers[driverId].lng = lng;
  if (available !== undefined) drivers[driverId].available = available;
  
  // Broadcast to connected users
  io.emit('driver-updated', { driverId, lat, lng, available });
  res.json({ success: true, driver: drivers[driverId] });
});

// Request Ride
app.post('/api/ride/request', (req, res) => {
  const { riderId, pickupLat, pickupLng, dropLat, dropLng } = req.body;
  const fare = calculateFare(pickupLat, pickupLng, dropLat, dropLng);
  
  const rideId = `RIDE-${Date.now()}`;
  activeRides[rideId] = {
    rideId,
    riderId,
    pickupLat, pickupLng,
    dropLat, dropLng,
    fare: fare.total,
    commission: fare.commission,
    driverPayout: fare.payout,
    status: 'requested',
    createdAt: new Date()
  };
  
  io.emit('ride-requested', activeRides[rideId]);
  res.json({ success: true, ride: activeRides[rideId] });
});

// Accept Ride
app.post('/api/ride/accept', (req, res) => {
  const { rideId, driverId } = req.body;
  if (!activeRides[rideId]) {
    return res.status(404).json({ error: 'Ride not found' });
  }
  activeRides[rideId].status = 'accepted';
  activeRides[rideId].driverId = driverId;
  activeRides[rideId].acceptedAt = new Date();
  
  if (drivers[driverId]) {
    drivers[driverId].available = false;
  }
  
  io.emit('ride-updated', activeRides[rideId]);
  res.json({ success: true, ride: activeRides[rideId] });
});

// Complete Ride
app.post('/api/ride/complete', (req, res) => {
  const { rideId } = req.body;
  if (!activeRides[rideId]) {
    return res.status(404).json({ error: 'Ride not found' });
  }
  activeRides[rideId].status = 'completed';
  activeRides[rideId].completedAt = new Date();
  
  // Update driver earnings
  const ride = activeRides[rideId];
  if (ride.driverId && drivers[ride.driverId]) {
    drivers[ride.driverId].totalTrips++;
    drivers[ride.driverId].totalEarnings += ride.driverPayout;
    drivers[ride.driverId].available = true;
  }
  
  // Track revenue
  dailyRevenue.totalZAR += ride.commission;
  
  io.emit('ride-completed', ride);
  res.json({ success: true, ride });
});

// Fare Calculator
function calculateFare(pickupLat, pickupLng, dropLat, dropLng, duration = 15) {
  const baseFare = 20;
  const ratePerKm = 10;
  const ratePerMin = 2;
  const commissionRate = 0.20;
  
  // Simple distance estimate
  const dLat = dropLat - pickupLat;
  const dLng = dropLng - pickupLng;
  const distanceKm = Math.sqrt(dLat*dLat + dLng*dLng) * 111;
  
  const distanceCost = distanceKm * ratePerKm;
  const timeCost = duration * ratePerMin;
  const subtotal = baseFare + distanceCost + timeCost;
  const commission = subtotal * commissionRate;
  
  return {
    total: Math.round(subtotal),
    commission: Math.round(commission),
    payout: Math.round(subtotal - commission),
    distanceKm: distanceKm.toFixed(2)
  };
}

